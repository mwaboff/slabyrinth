/**
 * `render rests`: measures where a thing set on each piece of the bundled palettes' furniture and stall roles rests (the
 * real top surface, scene3d `readRestSurface`) from the game's meshes, and writes core's generated table
 * `packages/core/src/palette/restHeights.ts`. Numbers only: one height per piece the palettes already name
 * (core `restPieces`), keyed by its asset id; nothing else read from the game is written. Re-run it after the palette
 * import (the import runs it when TaleSpire is installed), so new palette pieces get measured.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { loadPalettes, restPieces, type RestPiece } from "@slabyrinth/core";
import { readRestSurface } from "@slabyrinth/scene3d";
import { flag, type Args } from "./args";
import { REPO_ROOT } from "./inputs";
import { openMeshes } from "./meshes";
import type { Io, RenderEnv } from "./render3d";

export const USAGE_RESTS = `usage: npm run render -- rests [--install <folder>] [--dry]
  measures where things set on each piece of the bundled palettes' feature.* and stall.* roles rest, from the
  TaleSpire install (read-only), and writes packages/core/src/palette/restHeights.ts (--dry: print it only)`;

export const RESTS_FILE = join(REPO_ROOT, "packages", "core", "src", "palette", "restHeights.ts");

const r3 = (v: number): number => Math.round(v * 1000) / 1000;
const clean = (name: string): string => name.replace(/[\r\n*/]/g, " ").trim();

/** The generated file's text (already in the repository's Prettier style). */
export function restsFileText(
  measured: ReadonlyArray<{ piece: RestPiece; rest: number }>,
  unread: readonly RestPiece[],
): string {
  return [
    "/**",
    " * GENERATED by `npm run render -- rests` (packages/render-cli/src/rests.ts) from the TaleSpire install's meshes; do",
    " * not edit by hand. Re-run it after the palette import (which runs it when TaleSpire is installed).",
    " *",
    " * Where a thing set on a piece rests: the height of the piece's real top surface above its collider's bottom, in",
    " * tiles (the frame of the palette's `geom.size.y`), for every piece of the bundled palettes' feature.* and stall.*",
    " * roles, by asset id. palette/restSurface.ts reads it; a piece not listed rests at its collider's top.",
    " */",
    "export const MEASURED_RESTS: Readonly<Record<string, number>> = {",
    ...measured.map(({ piece, rest }) => `  "${piece.asset}": ${String(r3(rest))}, // ${clean(piece.name)}`),
    "};",
    "",
    "/** Pieces the measuring could not read (no mesh in the install): they rest at their collider's top. */",
    ...(unread.length === 0
      ? ["export const UNREAD_RESTS: readonly string[] = [];"]
      : [
          "export const UNREAD_RESTS: readonly string[] = [",
          ...unread.map((p) => `  "${p.asset}", // ${clean(p.name)}`),
          "];",
        ]),
    "",
  ].join("\n");
}

export async function renderRests(a: Args, io: Io, env: RenderEnv): Promise<number> {
  const meshes = await openMeshes({
    boxes: false,
    installFlag: flag(a, "install"),
    appData: null,
    ...(env.locate ? { locate: env.locate } : {}),
    log: (s) => {
      io.err(s);
    },
  });
  if (!meshes.install) {
    io.err(`rests: ${meshes.note} Nothing was measured; the table is unchanged.`);
    return 1;
  }
  const pieces = restPieces(loadPalettes().palettes);
  const looked = await meshes.source.load(pieces.map((p) => p.asset));
  const measured: Array<{ piece: RestPiece; rest: number }> = [];
  const unread: RestPiece[] = [];
  const dry = a.flags.has("dry");
  for (const piece of pieces) {
    const m = looked.get(piece.asset);
    const reading = m?.kind === "mesh" ? readRestSurface(m.mesh, m.geom ?? piece.geom) : null;
    if (reading) measured.push({ piece, rest: reading.rest });
    else unread.push(piece);
    if (dry)
      io.out(
        `${piece.name.padEnd(40)} box ${piece.geom.size.y.toFixed(3)} rest ${reading ? reading.rest.toFixed(3) : "-"} share ${reading ? reading.share.toFixed(2) : "-"}`,
      );
  }
  if (dry) return 0;
  writeFileSync(RESTS_FILE, restsFileText(measured, unread));
  io.out(
    `rests: measured ${String(measured.length)} pieces, ${String(unread.length)} unread; wrote ${RESTS_FILE}`,
  );
  return 0;
}
