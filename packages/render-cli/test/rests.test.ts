/**
 * `render rests` without a game: it measures nothing and leaves core's tables as they are; a table's text is what core
 * reads (readings by asset id, each with the collider it was read against, in the repository's style) and its header
 * states its body's hash. Never touches the install or the app's data.
 */
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { runRender } from "../src/index";
import { checkTableHash, parseRestGrid } from "@slabyrinth/core";
import {
  HANG_GRIDS_FILE,
  RESTS_FILE,
  coverFileText,
  hangGridsFileText,
  restGridText,
  restGridsFileText,
  restsFileText,
} from "../src/rests";

const geom = {
  size: { x: 1, y: 1.1, z: 1 },
  originAt: "center" as const,
  boundsCenter: { x: 0, y: 0.55, z: 0 },
  lengthAxis: "x" as const,
};
/** Read against a slightly different collider than the palette's (the install's). */
const against = { geom: { ...geom, size: { x: 1.0004, y: 1.1, z: 0.99951 } }, mesh: "0a1b2c3d" };

describe("render rests", () => {
  it("without TaleSpire it measures nothing and leaves the tables unchanged", async () => {
    const before = readFileSync(RESTS_FILE, "utf8");
    const hangBefore = readFileSync(HANG_GRIDS_FILE, "utf8");
    const err: string[] = [];
    const code = await runRender(
      ["rests"],
      { out: () => undefined, err: (s) => err.push(s) },
      { cwd: ".", appData: null, locate: () => Promise.resolve(null) },
    );
    expect(code).toBe(1);
    expect(err.join("\n")).toMatch(/Nothing was measured/);
    expect(readFileSync(RESTS_FILE, "utf8")).toBe(before);
    expect(readFileSync(HANG_GRIDS_FILE, "utf8")).toBe(hangBefore);
  });

  it("writes one height per piece by asset id with what it was read against, and the pieces it could not read", () => {
    const text = restsFileText(
      [{ piece: { asset: "aa", name: 'Bench */ "odd"', geom }, against, rest: 0.76543 }],
      [{ asset: "bb", name: "Unread", geom }],
    );
    expect(text).toMatch(/^\/\*\*\n \* GENERATED by `npm run render -- rests`/);
    expect(text).toContain(
      `  "aa": {\n    name: "Bench     odd",\n    rest: 0.765,\n    size: [1, 1.1, 1],\n    mesh: "0a1b2c3d",\n  },\n`,
    );
    expect(text).toContain(`export const UNREAD_RESTS: readonly string[] = [\n  "bb", // Unread\n];`);
    expect(checkTableHash(text).ok).toBe(true);
    expect(checkTableHash(text.replace("0.765", "0.8")).ok).toBe(false);
  });

  it("writes each grid as core parses it, from above and from below", () => {
    const grid = { nx: 2, nz: 2, heights: [0.75, null, 0.754, -0.02] };
    expect(restGridText(grid)).toBe("2x2:75 - 75 -2");
    expect(parseRestGrid(restGridText(grid))).toEqual({ nx: 2, nz: 2, heights: [0.75, null, 0.75, -0.02] });
    const top = restGridsFileText([{ piece: { asset: "aa", name: "Desk", geom }, against, grid }], []);
    expect(top).toContain(`  "aa": {\n    name: "Desk",\n    grid: "2x2:75 - 75 -2",\n`);
    const under = hangGridsFileText([{ piece: { asset: "cc", name: "Canopy", geom }, against, grid }], []);
    expect(under).toContain(`export const HANG_GRIDS: Readonly<Record<string, MeasuredGrid>> = {`);
    expect(under).toContain(`    grid: "2x2:75 - 75 -2",\n`);
    expect(checkTableHash(top).ok && checkTableHash(under).ok).toBe(true);
  });

  it("writes one floor hole per piece by asset id", () => {
    const text = coverFileText(
      [{ piece: { asset: "cc", name: "Rounded", geom }, against, hole: 0.35512 }],
      [],
    );
    expect(text).toContain(`    hole: 0.355,\n`);
    expect(text).toContain(`export const UNREAD_HOLES: readonly string[] = [];`);
  });
});
