/**
 * `render rests` without a game: it measures nothing and leaves core's table as it is; the table's text is what core
 * reads (numbers by asset id, in the repository's style). Never touches the install or the app's data.
 */
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { runRender } from "../src/index";
import { parseRestGrid } from "@slabyrinth/core";
import { RESTS_FILE, coverFileText, restGridText, restGridsFileText, restsFileText } from "../src/rests";

const geom = {
  size: { x: 1, y: 1.1, z: 1 },
  originAt: "center" as const,
  boundsCenter: { x: 0, y: 0.55, z: 0 },
  lengthAxis: "x" as const,
};

describe("render rests", () => {
  it("without TaleSpire it measures nothing and leaves the table unchanged", async () => {
    const before = readFileSync(RESTS_FILE, "utf8");
    const err: string[] = [];
    const code = await runRender(
      ["rests"],
      { out: () => undefined, err: (s) => err.push(s) },
      { cwd: ".", appData: null, locate: () => Promise.resolve(null) },
    );
    expect(code).toBe(1);
    expect(err.join("\n")).toMatch(/Nothing was measured/);
    expect(readFileSync(RESTS_FILE, "utf8")).toBe(before);
  });

  it("writes one height per piece by asset id, and the pieces it could not read", () => {
    const geom = {
      size: { x: 1, y: 1.1, z: 1 },
      originAt: "center" as const,
      boundsCenter: { x: 0, y: 0.55, z: 0 },
      lengthAxis: "x" as const,
    };
    const text = restsFileText(
      [{ piece: { asset: "aa", name: "Bench */ odd", geom }, rest: 0.76543 }],
      [{ asset: "bb", name: "Unread", geom }],
    );
    expect(text).toMatch(/^\/\*\*\n \* GENERATED by `npm run render -- rests`/);
    expect(text).toContain(`  "aa": 0.765, // Bench    odd\n`);
    expect(text).toContain(`export const UNREAD_RESTS: readonly string[] = [\n  "bb", // Unread\n];`);
  });

  it("writes each rest grid as core parses it, its value on the next line when the entry is long", () => {
    const grid = { nx: 2, nz: 2, heights: [0.75, null, 0.754, 1.1] };
    expect(restGridText(grid)).toBe("2x2:75 - 75 110");
    expect(parseRestGrid(restGridText(grid))).toEqual({ nx: 2, nz: 2, heights: [0.75, null, 0.75, 1.1] });
    const short = restGridsFileText([{ piece: { asset: "aa", name: "Desk", geom }, grid }], []);
    expect(short).toContain(`  "aa": "2x2:75 - 75 110", // Desk\n`);
    const big = { nx: 12, nz: 12, heights: Array.from({ length: 144 }, () => 0.5) };
    const long = restGridsFileText([{ piece: { asset: "aa", name: "Table", geom }, grid: big }], []);
    expect(long).toContain(`  "aa":\n    "12x12:50 50`);
  });

  it("writes one floor hole per piece by asset id", () => {
    const text = coverFileText([{ piece: { asset: "cc", name: "Rounded", geom }, hole: 0.35512 }], []);
    expect(text).toContain(`  "cc": 0.355, // Rounded\n`);
    expect(text).toContain(`export const UNREAD_HOLES: readonly string[] = [];`);
  });
});
